SELECT
    Dep.DepartmentName,
    COUNT(B.TotalAmount) AS Revenue
FROM Billing B
JOIN Admissions A
    ON B.AdmissionID = A.AdmissionID
JOIN Department Dep
    ON A.DepartmentID = Dep.DepartmentID
GROUP BY Dep.DepartmentName
ORDER BY Revenue DESC;

